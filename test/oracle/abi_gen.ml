(* ABI generator: emits GNU-assembler source for a v3 execution-ABI helper
   (asm/docs/exec-abi-v3.md), one profile at a time (.ai/asm_plan.md M4 Phase
   3). x86_64 and x86_32 are implemented, per Phase 3.4's ordering - prove one
   profile end to end before generalizing, and x86_32 next because Phase 5's
   fixture needs it.

   Design (see abi_gen_text.ml's header for [verbatim_block]'s rationale):
   the v1 logic in [helpers/x86_64.s] is reused character-for-character via
   [verbatim_block], split at exactly the points where v3 needs to insert new
   logic. Everything that differs by ABI version is wrapped in a GAS
   [.if ABI_VERSION >= 3 ... .else ... .endif] (or [.if ... .endif] when v1/v2
   need no counterpart), so the SAME generated source, assembled with
   [--defsym ABI_VERSION=1] or [=2], reproduces the frozen helper's v1/v2
   behavior byte-for-byte - checked directly in [test_abi_gen.ml] against the
   real checked-in file, with no helper or QEMU involved. That self-check is
   what makes "prove x86_64" a two-part claim: the v1/v2 path is proven by
   textual equality with a file that has already passed years of conformance
   runs, and only the genuinely new v3 path needs a fresh QEMU proof.

   New v3 logic added at each splice point (exec-abi-v3.md §§2-4):
     - stage 3: n_expected accepts 1..8 rather than forced to 1, and is saved
       to a new .bss slot (v3_n_expected) for later stages to read;
     - a new .bss block for v3-only state: v3_n_expected, v3_obs_table_off
       (the observation-descriptor table's offset, derived per §2, not
       stored), v3_manifest_base (the manifest's mapped base - saved
       separately from the %r15 register value, because nothing may trust a
       register across the guest call: "Anything that must survive the guest
       call is reloaded from .bss PC-relatively afterwards" per the frozen
       helper's own header comment, and %r15 is exactly such a register);
     - stage 4b: the observation-descriptor table's own bound check, then
       per-descriptor width/reserved/containment/readability validation,
       entirely from the manifest's own descriptors - no guest memory is
       read here (exec-abi-v3.md §3);
     - the v1 step-9 publish, generalized to copy every expected[] entry
       (not just slot 0) and to record the real n_expected;
     - the post-return tail, generalized to load each additional observation
       from guest memory (using v3_manifest_base, never %r15) and to decide
       passed/failed by comparing every slot, not just slot 0
       (exec-abi-v3.md §4). *)

open Abi_gen_text

type profile = X86_64 | X86_32 | Arm | Aarch64

let profile_name = function
  | X86_64 -> "x86_64"
  | X86_32 -> "x86_32"
  | Arm -> "arm"
  | Aarch64 -> "aarch64"

(* ---- segment A0a: header comment through the shared-constants include ---- *)

let seg_a0a =
  {|/* Execution ABI helper - profile 2, x86-64 SysV.
 *
 * GENERATED by test/oracle/abi_gen_main.ml (.ai/asm_plan.md M4 Phase 3). Do
 * not hand-edit: v1/v2 behavior is a byte-for-byte reproduction of the
 * frozen asm/helpers/x86_64.s, and v3 behavior is documented at each
 * ".if ABI_VERSION >= 3" splice point below and in asm/docs/exec-abi-v3.md.
 *
 * Implements asm/docs/exec-abi-v1.md §4 step by step, and asm/docs/exec-abi-v3.md
 * §§2-4 when assembled with ABI_VERSION >= 3. Direct Linux syscalls only: no
 * C, no libc, no dynamic loader. Assembled and linked by the reference GNU
 * as/ld (tools/asm-helpers.sh) and run under qemu-x86_64.
 *
 * Invocation:  helper <manifest-path> <result-path>
 *
 * The structure follows the document rather than what would be convenient in
 * assembly, and in two places that is the entire point:
 *
 *   - the result fd is mapped twice, once at a kernel-selected control address
 *     and once at the normative result_addr, so an error channel exists before
 *     anything can fail validation and no positioned-write path is needed;
 *
 *   - every mapping, protection change and cache operation happens *before* the
 *     running commit, so that a helper fault in those steps and a deliberate
 *     guest trap do not produce the same wait status (§15.1).
 *
 * Register conventions inside the validator (no syscalls run there, so the
 * syscall-clobbered rcx/r11 are free):
 *
 *   r15  manifest mapping base        r14  st_size (trusted, from fstat)
 *   r13  control alias (result page)  r12  n_segments
 *   rbx  loop index                   rcx  current descriptor pointer
 *
 * Anything that must survive the guest call is reloaded from .bss
 * PC-relatively afterwards. §11 keeps a copy of the helper SP in rbx as a
 * convenience, but recovery never depends on the guest having preserved it. */

        .include "abi-v1.inc"|}
  |> verbatim_block

